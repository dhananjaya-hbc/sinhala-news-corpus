"""Regenerate STATS.md from data/raw/*.csv.

Usage: python scripts/stats.py [--data-dir data/raw] [--config sources.yaml] [--out STATS.md]

The output depends only on the data (no "generated at" clock time), so
STATS.md changes exactly when the data does.
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from collector.categories import LABELS  # noqa: E402
from collector.config import load_config  # noqa: E402
from collector.storage import read_rows  # noqa: E402


def _pct(n: int, total: int) -> str:
    return f"{100 * n / total:.1f}%" if total else "0.0%"


def _table(header: list[str], rows: list[list[str]], align: list[str]) -> list[str]:
    sep = {"l": "---", "r": "---:"}
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join(sep[a] for a in align) + " |"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return lines


def render(rows: list[dict[str, str]], source_names: dict[str, tuple[str, str]]) -> str:
    total = len(rows)
    by_source = Counter(r["source"] for r in rows)
    by_category = Counter(r["category"] for r in rows)
    by_month = Counter(r["collected_at"][:7] for r in rows)
    cross = Counter((r["source"], r["category"]) for r in rows)
    dates = sorted(r["date"] for r in rows)
    last = max((r["collected_at"] for r in rows), default="-")

    out = ["# Dataset statistics", "", "_Generated by `scripts/stats.py` after each daily run._", ""]
    out += [
        f"- **Total headlines:** {total:,}",
        f"- **Sources:** {len(by_source)}",
        f"- **Headline dates:** {dates[0]} to {dates[-1]}" if dates else "- **Headline dates:** -",
        f"- **Last collected:** {last}",
        "",
    ]

    out += ["## Headlines per source", ""]
    src_rows = []
    for src, n in sorted(by_source.items(), key=lambda kv: (-kv[1], kv[0])):
        name, url = source_names.get(src, (src, ""))
        label = f"[{name}]({url})" if url else name
        src_rows.append([label, f"`{src}`", f"{n:,}", _pct(n, total)])
    out += _table(["Source", "id", "Headlines", "Share"], src_rows, ["l", "l", "r", "r"]) + [""]

    out += ["## Headlines per category", ""]
    cat_rows = [[f"`{c}`", f"{by_category[c]:,}", _pct(by_category[c], total)] for c in LABELS]
    out += _table(["Category", "Headlines", "Share"], cat_rows, ["l", "r", "r"]) + [""]

    out += ["## Source x category", ""]
    sources = sorted(by_source)
    cross_rows = [[f"`{c}`"] + [f"{cross[(s, c)]:,}" for s in sources] for c in LABELS]
    out += _table(["Category"] + [f"`{s}`" for s in sources], cross_rows, ["l"] + ["r"] * len(sources)) + [""]

    out += ["## Headlines per month file", ""]
    month_rows = [[f"[`{m}.csv`](data/raw/{m}.csv)", f"{n:,}"] for m, n in sorted(by_month.items())]
    out += _table(["File", "Headlines"], month_rows, ["l", "r"]) + [""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Regenerate STATS.md")
    parser.add_argument("--data-dir", default="data/raw")
    parser.add_argument("--config", default="sources.yaml")
    parser.add_argument("--out", default="STATS.md")
    args = parser.parse_args(argv)

    names = {}
    if Path(args.config).exists():
        names = {s.id: (s.name, s.homepage) for s in load_config(args.config).sources}
    rows = list(read_rows(args.data_dir))
    Path(args.out).write_text(render(rows, names), encoding="utf-8")
    print(f"wrote {args.out}: {len(rows)} headlines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
